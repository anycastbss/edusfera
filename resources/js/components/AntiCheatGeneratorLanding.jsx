export function getSamplePreview(subject, grade) {
    const numGrade = isNaN(parseInt(grade, 10)) ? 11 : parseInt(grade, 10);
    if (subject === 'math') {
        if (numGrade <= 6) return SAMPLE_PREVIEWS.math_grade_5_6;
        if (numGrade === 7) return SAMPLE_PREVIEWS.math_grade_7;
        if (numGrade <= 9) return SAMPLE_PREVIEWS.math_grade_8_9;
        return SAMPLE_PREVIEWS.math;
    }
    return SAMPLE_PREVIEWS[subject] || SAMPLE_PREVIEWS.math;
}

