   - В тестовых заданиях строго 4 варианта ответа: 1), 2), 3), 4).
   - Запрещено ставить случайные бессмысленные фразы или числа!
   - 1 вариант — абсолютно верный.
   - Остальные 3 варианта — это РЕЗУЛЬТАТЫ РЕАЛЬНЫХ ТИПИЧНЫХ ОШИБОК школьников.

