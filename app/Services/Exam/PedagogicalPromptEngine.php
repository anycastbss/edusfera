   - В языках (русский, белорусский, английский): словарное слово, термин или номера предложений.

3. ДИСТРАКТОРЫ В ТЕСТОВЫХ ЗАДАНИЯХ — ЭТО ТИПИЧНЫЕ ОШИБКИ УЧЕНИКОВ:
   - В тестовых заданиях строго 4 варианта ответа: 1), 2), 3), 4).
   - Запрещено ставить случайные бессмысленные фразы или числа!
   - 1 вариант — абсолютно верный.
   - Остальные 3 варианта — это РЕЗУЛЬТАТЫ РЕАЛЬНЫХ ТИПИЧНЫХ ОШИБОК школьников.

4. АНТИ-СПИСЫВАНИЕ И ПАРАЛЛЕЛЬНОСТЬ:
   - Все {$variantCount} вариантов должны иметь идентичную сложность, но РАЗНЫЕ сюжетные фабулы, разные числовые коэффициенты и разные исторические/лингвистические примеры.

5. ТРЕБОВАНИЯ К ТЕКСТУ И ФОРМУЛАМ (ДЛЯ ПЕЧАТИ В PDF):
   - ⛔ СТРОЖАЙШИЙ ЗАПРЕТ НА LaTeX: не используй символы $ или $$, обратные слэши (\\frac, \\sqrt, \\cdot).
   - Все формулы пиши ТОЛЬКО чистым текстом и знаками Юникода: √x, x², x³, ·, ≤, ≥, ±, (a + b) / c.
   - ⛔ ЗАПРЕТ НА ЧЕРНОВЫЕ РАССУЖДЕНИЯ («Стоп», «пересчитаем», «исправляем», «заменяем ответ»). Выдавай только безупречный чистовик!

