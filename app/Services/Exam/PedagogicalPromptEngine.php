<?php

declare(strict_types=1);

namespace App\Services\Exam;

use App\Models\GeneratorOrder;

/**
 * PedagogicalPromptEngine — экспертный методический генератор промптов для Edusfera.
 * 
 * Превращает сырые запросы пользователя в академически выверенные педагогические
 * спецификации с учетом стандартов образования Республики Беларусь, возраста (5-11 классы),
 * типа работы (самостоятельная, контрольная, диагностика, экспресс-тест, ЦТ/ЦЭ)
 * и формата оформления (традиционный школьный № 1..N для младших/средних классов
 * либо экзаменационный Часть А / Б для 10-11 кл).
 */
class PedagogicalPromptEngine
{
    /**
     * Собрать комплексный методический запрос (системную инструкцию и промпт)
     *
     * @return array{system: string, prompt: string, exam_format: string}
     */
    public static function build(GeneratorOrder $order): array
    {
        $payload = is_array($order->payload) ? $order->payload : [];

        $subject = htmlspecialchars(strip_tags(trim((string) $order->subject)), ENT_QUOTES, 'UTF-8');
        $topic = htmlspecialchars(strip_tags(trim((string) $order->topic)), ENT_QUOTES, 'UTF-8');
        $grade = (string) ($payload['grade'] ?? '7');
        $workType = (string) ($payload['work_type'] ?? 'independent');
        $difficulty = (string) ($payload['difficulty'] ?? 'base');

        $numGrade = is_numeric($grade) ? (int) $grade : 11;
        $rawFormat = (string) ($payload['exam_format'] ?? '');
        $isSchool = ($rawFormat === 'school') || ($rawFormat === '' && $numGrade < 10 && $workType !== 'ct_ce');
        $examFormat = $isSchool ? 'school' : 'exam';

        $variantCount = min(25, max(1, (int) ($order->variant_count ?: 5)));
        $countA = max(1, min(10, (int) ($payload['count_a'] ?? 2)));
        $countB = max(0, min(10, (int) ($payload['count_b'] ?? 1)));
        $totalTasks = $countA + $countB;

        $subjectDomain = self::detectSubjectDomain($subject);
        $gradeContext = self::buildGradeContext($grade, $subject);
        $workTypeContext = self::buildWorkTypeContext($workType);
        $difficultyContext = self::buildDifficultyContext($difficulty);
        $domainGuidelines = self::buildDomainGuidelines($subjectDomain, $grade, $subject);
        $taskBlueprint = self::buildTaskBlueprint($countA, $countB, $subjectDomain, $grade, $isSchool);

        $systemInstruction = self::buildSystemInstruction($subjectDomain, $grade, $workType, $isSchool);

        if ($isSchool) {
            $structureDesc = sprintf("Всего %d %s (№ 1–%d): %d с выбором ответа и %d с кратким/числовым ответом",
                $totalTasks, self::pluralTasks($totalTasks), $totalTasks, $countA, $countB);
            $formatNotice = "ФОРМАТ ОФОРМЛЕНИЯ: КЛАССИЧЕСКИЙ ШКОЛЬНЫЙ ФОРМАТ ДЛЯ МЛАДШИХ И СРЕДНИХ КЛАССОВ (НЕ ЦТ/ЦЭ!):\n".
                "- Задания нумеруются строго сквозным порядком: «**Задание 1:**», «**Задание 2:**», «**Задание 3:**» (до Задания {$totalTasks}).\n".
                "- ⛔ СТРОЖАЙШЕ ЗАПРЕЩЕНО использовать деление на Часть А и Часть Б, а также приставки А1, А2, Б1! Для школьников {$numGrade} класса работа должна выглядеть как привычный школьный сборник самостоятельных/контрольных работ.\n".
                "- Первые {$countA} заданий оформляются с 4 вариантами ответов: 1), 2), 3), 4).\n".
                ($countB > 0 ? "- Следующие {$countB} заданий оформляются с открытым ответом (без вариантов, с полем Ответ: целое число или термин).\n" : "");
        } else {
            $partADesc = sprintf("%d %s Части А (с выбором 1 верного ответа из 4)", $countA, self::pluralTasks($countA));
            $partBDesc = $countB > 0 
                ? sprintf("%d %s Части Б (%s)", $countB, self::pluralTasks($countB), self::getPartBFormatDescription($subjectDomain)) 
                : "без Части Б";
            $structureDesc = "{$partADesc} и {$partBDesc}";
            $formatNotice = "ФОРМАТ ОФОРМЛЕНИЯ: ЭКЗАМЕНАЦИОННЫЙ СТАНДАРТ ЦТ / ЦЭ 2026:\n".
                "- Задания Части А нумеруются как «**Задание А1:**», «**Задание А2:**»...\n".
                "- Задания Части Б нумеруются как «**Задание Б1:**»...\n".
                "- Полное соответствие спецификациям экзаменов Республики Беларусь.";
        }

        $prompt = <<<PROMPT
════════════════════════════════════════════════════════════════
МЕТОДИЧЕСКИЙ БРИФ ДЛЯ СОСТАВИТЕЛЯ ПРОВЕРОЧНЫХ РАБОТ EDUSFERA
════════════════════════════════════════════════════════════════

<педагогический_паспорт_заказа>
• Дисциплина: {$subject}
• Тема занятия: {$topic}
• Класс / Возрастная группа: {$gradeContext['label']} ({$gradeContext['stage_desc']})
• Тип учебной работы: {$workTypeContext['title']} ({$workTypeContext['duration']}, цель: {$workTypeContext['goal']})
• Формат бланка: {$formatNotice}
• Уровень сложности: {$difficultyContext['title']} ({$difficultyContext['desc']})
• Количество параллельных вариантов: {$variantCount} шт.
• Структура каждого варианта: {$structureDesc}
</педагогический_паспорт_заказа>

{$gradeContext['curriculum_requirements']}

{$workTypeContext['pedagogical_instructions']}

{$domainGuidelines}

════════════════════════════════════════════════════════════════
ДИДАКТИЧЕСКИЙ КОДИФИКАТОР ЗАДАНИЙ (СТРОГИЙ ПЛАН):
════════════════════════════════════════════════════════════════
Каждый из {$variantCount} вариантов ОБЯЗАН быть строго параллелен по когнитивной сложности и проверять следующие дидактические единицы:
{$taskBlueprint}

════════════════════════════════════════════════════════════════
