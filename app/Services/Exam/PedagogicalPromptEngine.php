    /**
     * Плюрализация слова "задание"
     */
    protected static function pluralTasks(int $count): string
    {
        $c = abs($count) % 100;
        $c1 = $c % 10;

        if ($c > 10 && $c < 20) {
            return 'заданий';
        }
        if ($c1 > 1 && $c1 < 5) {
            return 'задания';
        }
        if ($c1 === 1) {
            return 'задание';
        }

        return 'заданий';
    }
