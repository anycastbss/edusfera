   - Все формулы пиши ТОЛЬКО чистым текстом и знаками Юникода: √x, x², x³, ·, ≤, ≥, ±, (a + b) / c.
   - ⛔ ЗАПРЕТ НА ЧЕРНОВЫЕ РАССУЖДЕНИЯ («Стоп», «пересчитаем», «исправляем», «заменяем ответ»). Выдавай только безупречный академический чистовик!

