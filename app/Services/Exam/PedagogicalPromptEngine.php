════════════════════════════════════════════════════════════════
1. СТРОЖАЙШИЙ ЗАПРЕТ НА ОДНООБРАЗНЫЕ ОТВЕТЫ (ВСЕ "1" ИЛИ ВСЕ "А"):
   - ⛔ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО делать вариант, где правильный ответ всегда под номером 1 (или буквой А)!
   - В КАЖДОМ варианте правильные ответы ОБЯЗАНЫ равномерно распределяться между номерами 1, 2, 3 и 4.
   - Пример идеального чередования в варианте: Задание 1 — ответ 3; Задание 2 — ответ 1; Задание 3 — ответ 4; Задание 4 — ответ 2!

2. СПЕЦИФИКА ПРЕДМЕТА И ОТВЕТОВ К ЧАСТИ Б / ОТКРЫТЫМ ЗАДАНИЯМ:
   - В точных науках (математика, физика, химия): ответом к открытым задачам является СТРОГО КОНКРЕТНОЕ ЦЕЛОЕ ЧИСЛО (например, 14, -2, 25). Сначала выбери число, затем составь задачу под него.
