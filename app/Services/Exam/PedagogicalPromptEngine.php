   - Все математические выражения, уравнения, дроби, корни и переменные оформляй в стандартной нотации Word/LaTeX между знаками доллара $...$:
     * Квадратные и n-е корни: СТРОГО $\sqrt{...}$ с полным выражением под знаком корня (например: $\sqrt{2x + 7} = x - 4$, $\sqrt{x^2 - 5x + 6} \cdot \sqrt{x - 1} = 0$). Категорически запрещено писать сырые текстовые суррогаты вида «√(x+1)»!
