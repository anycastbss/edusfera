6. ⚖️ СТРОЖАЙШИЙ ЗАКОН СИММЕТРИИ ВАРИАНТОВ (КРИТИЧЕСКИЙ СТАНДАРТ EDUSFERA):
   - В КАЖДОМ БЕЗ ИСКЛЮЧЕНИЯ ВАРИАНТЕ должно быть СТРОГО РОВНО {$countA} заданий с выбором ответа (Часть А) и РОВНО {$countB} заданий с кратким ответом (Часть Б)!
   - Итого в КАЖДОМ варианте РОВНО {$totalTasks} заданий! Ни на одно задание больше, ни на одно меньше!
   - ⛔ СТРОЖАЙШЕ ЗАПРЕЩЕНА АСИММЕТРИЯ: категорически запрещено добавлять 6-е задание в Вариант 2, если в Варианте 1 пять заданий! Любая асимметрия срывает дисциплину в классе и ломает мастер-таблицу учителя.
