════════════════════════════════════════════════════════════════
1. МЕТОДИКА СОСТАВЛЕНИЯ «ОТ ПРЕДОПРЕДЕЛЕННОГО ОТВЕТА»:
   - В точных науках (математика, физика, химия): СНАЧАЛА выбери красивое целое число в качестве ответа (например, x = 3, x = -2), затем составь под него корректное условие.
   - В Части Б ответом в точных науках ВСЕГДА должно быть СТРОГО ЦЕЛОЕ ЧИСЛО (без корней, без дробей).
   - В гуманитарных науках ответом в Части Б является код соответствия (А2Б1В4Г3), числовая комбинация или точный термин в именительном падеже.

2. ДИСТРАКТОРЫ В ЧАСТИ А — ЭТО ТИПИЧНЫЕ ОШИБКИ УЧЕНИКОВ:
   - В Части А строго 4 варианта ответа: 1), 2), 3), 4).
   - Запрещено ставить случайные бессмысленные числа!
   - 1 вариант — абсолютно верный.
   - Остальные 3 варианта — это РЕЗУЛЬТАТЫ РЕАЛЬНЫХ ТИПИЧНЫХ ОШИБОК школьников (например: потеря знака минус, раскрытие скобки только для первого слагаемого, ошибка формулы).
