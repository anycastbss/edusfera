    /**
     * Проверка, требуется ли генерация комплексного полного варианта ЦЭ/ЦТ по всей программе
     */
    public static function isFullExamVariant(string $topic, string $workType, string $examFormat): bool
    {
        $t = mb_strtolower(trim($topic));
        if ($workType === 'ct_ce' || $workType === 'exam') {
            return true;
        }

        $fullExamKeywords = [
            'полный вариант', 'весь курс', 'комплексный вариант', 'пробный вариант',
            'пробный экзамен', 'итоговый практикум', 'цэ', 'цт', 'все разделы',
            'генеральная репетиция', 'тренинг цт', 'тренинг цэ', 'спецификация'
        ];

        foreach ($fullExamKeywords as $kw) {
            if (str_contains($t, $kw)) {
                return true;
            }
        }

        return false;
    }

