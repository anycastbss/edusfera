════════════════════════════════════════════════════════════════
PROMPT;

        $sampleAnswerB = in_array($subjectDomain, ['history', 'social'])
            ? 'А2Б1В4Г3 (или точный термин в им. падеже: Статут ВКЛ)'
            : (in_array($subjectDomain, ['russian', 'belarusian', 'english']) ? 'преданность' : '14');

        if ($isSchool) {
