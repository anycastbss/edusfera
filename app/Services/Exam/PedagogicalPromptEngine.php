    /**
     * Построение дидактического кодификатора заданий
     */
    protected static function buildTaskBlueprint(int $countA, int $countB, string $domain, string $grade, bool $isSchool = false): string
    {
        $lines = [];

        for ($i = 1; $i <= $countA; $i++) {
            $numLabel = $isSchool ? "Задание {$i}" : "Задание А{$i}";
            $level = match ($i) {
                1 => 'Базовый уровень (распознавание правила / элементарный стандартный пример темы)',
                2 => 'Средний уровень (применение алгоритма в 2 шага, содержит дидактическую ловушку со знаками/исключениями)',
                3 => 'Достаточный уровень (комбинированное преобразование или практический контекст)',
                4 => 'Повышенный уровень (несколько взаимосвязанных шагов / анализ условия)',
                default => 'Углубленный уровень сложности',
            };

            $lines[] = "• {$numLabel}: {$level}. 4 варианта ответа, из которых 3 дистрактора отражают типичные ошибки.";
        }

        for ($j = 1; $j <= $countB; $j++) {
            $taskIdx = $countA + $j;
            $numLabel = $isSchool ? "Задание {$taskIdx}" : "Задание Б{$j}";
            $format = match ($domain) {
                'history', 'social' => 'установление соответствия между понятиями/датами (ответ вида А2Б1В4Г3) либо точный исторический термин в им. падеже (без счета лет!)',
                'russian', 'belarusian', 'english' => 'слово в начальной форме / термин / номер предложения',
                default => 'задача повышенной сложности с открытым ответом — СТРОГО ЦЕЛОЕ ЧИСЛО (без корней и дробей)',
            };

            $lines[] = "• {$numLabel}: Высокий уровень сложности ({$format}). Без вариантов ответа.";
        }

        return implode("\n", $lines);
    }

