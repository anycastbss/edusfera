    /**
     * Определение предметной области
     */
    public static function detectSubjectDomain(string $subject): string
    {
        $sub = mb_strtolower(trim($subject));

        if (str_contains($sub, 'математ') || str_contains($sub, 'алгебр') || str_contains($sub, 'геометр')) {
            return 'math';
        }
        if (str_contains($sub, 'физик') || str_contains($sub, 'астроном')) {
            return 'physics';
        }
        if (str_contains($sub, 'хим')) {
            return 'chemistry';
        }
        if (str_contains($sub, 'биолог')) {
            return 'biology';
        }
        if (str_contains($sub, 'русск')) {
            return 'russian';
        }
        if (str_contains($sub, 'белорус') || str_contains($sub, 'беларуск')) {
            return 'belarusian';
        }
        if (str_contains($sub, 'англ') || str_contains($sub, 'english')) {
            return 'english';
        }
        if (str_contains($sub, 'истор')) {
            return 'history';
        }
        if (str_contains($sub, 'обществ')) {
            return 'social';
        }
        if (str_contains($sub, 'информ') || str_contains($sub, 'it') || str_contains($sub, 'программир')) {
            return 'it';
        }

        return 'general';
    }

    /**
     * Контекст класса и учебной программы РБ
     */
    protected static function buildGradeContext(string $grade, string $subject): array
    {
        $numGrade = is_numeric($grade) ? (int) $grade : 11;

        if ($grade === 'abiturient' || $numGrade >= 10) {
            return [
                'short_label' => $grade === 'abiturient' ? 'Абитуриент' : "{$numGrade} класс",
                'label' => $grade === 'abiturient' ? 'Абитуриент (подготовка к ЦТ/ЦЭ)' : "{$numGrade} класс (старшая школа)",
                'stage_desc' => 'Профильная старшая ступень, формат экзаменов ЦТ/ЦЭ 2026',
                'curriculum_requirements' => "ТРЕБОВАНИЯ ПРОГРАММЫ СТАРШЕЙ ШКОЛЫ И ЦТ/ЦЭ 2026:\n".
                    "- Задания должны соответствовать официальным спецификациям экзаменов ЦТ/ЦЭ Беларуси 2026 года.\n".
                    "- Высокая плотность дидактических ловушек, комбинированные многошаговые решения, строгий академический язык.\n".
                    "- В Части А: выбор 1 из 4 вариантов. В Части Б: открытый ответ (целое число или код).",
            ];
        }

        if ($numGrade >= 7) {
            return [
                'short_label' => "{$numGrade} класс",
                'label' => "{$numGrade} класс (базовая школа)",
                'stage_desc' => 'Основное общее среднее образование РБ',
                'curriculum_requirements' => "ТРЕБОВАНИЯ УЧЕБНОЙ ПРОГРАММЫ МИНИСТЕРСТВА ОБРАЗОВАНИЯ РБ ({$numGrade} КЛАСС):\n".
                    "- Задания СТРОГО соответствуют программе {$numGrade} класса учреждений общего среднего образования РБ!\n".
                    "- ⛔ ЗАПРЕЩЕНО использовать понятия и темы старших классов (например, параметры, комплексные системы, высшую тригонометрию), если они не входят в курс {$numGrade} класса!\n".
                    "- Формулировки должны быть доступными, четкими и методически грамотными для школьника {$numGrade} класса.",
            ];
        }

        // 5 - 6 классы
        return [
            'short_label' => "{$numGrade} класс",
            'label' => "{$numGrade} класс (младшая средняя школа)",
            'stage_desc' => 'Начальный этап средней школы',
            'curriculum_requirements' => "ТРЕБОВАНИЯ УЧЕБНОЙ ПРОГРАММЫ МИНОБР РБ ДЛЯ {$numGrade} КЛАССА:\n".
                "- Задания должны быть наглядными, простыми и опираться на жизненный контекст.\n".
                "- Категорически запрещены абстрактные громоздкие алгебраические конструкции.\n".
                "- В математике: упор на натуральные числа, обыкновенные и десятичные дроби, простые уравнения на нахождение неизвестного компонента действий, текстовые сюжетные задачи.\n".
                "- В языках: базовые орфографические и пунктуационные правила курса {$numGrade} класса.",
